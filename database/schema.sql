-- =====================================================================
-- NexoMarket - Esquema de la base de datos (PostgreSQL 14 o superior)
-- Reconstruido a partir de las consultas SQL del backend. Crea las tablas
-- que usan AuthController, ProductController, OrderController y los
-- repositorios JDBC de los patrones de la PC3.
--
-- Uso:
--   CREATE DATABASE "NexoMarket";
--   psql -U postgres -d NexoMarket -f database/schema.sql
--   psql -U postgres -d NexoMarket -f database/datos_demo.sql
-- =====================================================================

CREATE TABLE IF NOT EXISTS rol (
    id_rol      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_rol  VARCHAR(30) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS cliente (
    id_cliente  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre      VARCHAR(120) NOT NULL,
    email       VARCHAR(160) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS usuario (
    id_usuario     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_rol         INTEGER NOT NULL REFERENCES rol (id_rol),
    id_cliente     INTEGER REFERENCES cliente (id_cliente),
    email          VARCHAR(160) NOT NULL UNIQUE,
    password_hash  VARCHAR(100) NOT NULL,
    activo         BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS categoria (
    id_categoria      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_categoria  VARCHAR(80) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS producto (
    id_producto   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_categoria  INTEGER NOT NULL REFERENCES categoria (id_categoria),
    nombre        VARCHAR(120) NOT NULL,
    precio        NUMERIC(10, 2) NOT NULL CHECK (precio > 0),
    stock         INTEGER NOT NULL CHECK (stock >= 0)
);

-- Estados del patrón State. CONFIRMADO se conserva solo por compatibilidad con la PC2.
CREATE TABLE IF NOT EXISTS pedido (
    id_pedido     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente    INTEGER NOT NULL REFERENCES cliente (id_cliente),
    monto_total   NUMERIC(12, 2) NOT NULL CHECK (monto_total >= 0),
    estado        VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE'
                  CHECK (estado IN ('PENDIENTE', 'PAGADO', 'CONFIRMADO', 'PREPARANDO',
                                    'ENVIADO', 'ENTREGADO', 'CANCELADO')),
    fecha_pedido  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS detalle_pedido (
    id_detalle_pedido  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pedido          INTEGER NOT NULL REFERENCES pedido (id_pedido),
    id_producto        INTEGER NOT NULL REFERENCES producto (id_producto),
    cantidad           INTEGER NOT NULL CHECK (cantidad > 0),
    precio_unitario    NUMERIC(10, 2) NOT NULL CHECK (precio_unitario >= 0)
);
